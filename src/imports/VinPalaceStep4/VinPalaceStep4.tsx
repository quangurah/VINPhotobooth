const trackAction = async (action: "download" | "share") => {
  const sessionId = localStorage.getItem("diSanSessionId");
  if (!sessionId) return;
  try {
    await fetch(`${BASE_URL}/tclife/track-action`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json"
      },
      body: JSON.stringify({ sessionId, action })
    });
  } catch (e) {
    console.error("Lỗi track action:", e);
  }
};

const handleDownloadCommon = (navigateFn?: any) => {
  const resultImage = localStorage.getItem("diSanResultImage");
  if (!resultImage) {
    if (typeof navigateFn === "function") navigateFn('/vinpalacestep5');
    return;
  }

  const link = document.createElement("a");
  link.href = resultImage;
  link.download = `tap_chi_di_san_${Date.now()}.jpg`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);

  trackAction("download");

  if (typeof navigateFn === "function") {
    setTimeout(() => {
      navigateFn('/vinpalacestep5');
    }, 500);
  }
};

